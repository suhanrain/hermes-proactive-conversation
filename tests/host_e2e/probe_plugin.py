"""Hook-argument probe: a second plugin, installed the same way, that records what the hook is handed.

One question only the *host* can answer: what do the arguments of a ``pre_gateway_dispatch``
callback actually look like once hermes' own loader has registered it? The plugin under test does
its job and says nothing, so this probe is installed beside it in the same throwaway home — same
loader, same invocation path, same event, same install form — and writes one JSON line per real
invocation: the pid that ran it, the configured isolation mode, the runtime types, and the result of
actually calling the two real methods the policy needs (``session_store.peek_session_id`` and
``gateway._is_session_running``).

Two further things are recorded on the same run, because the question "can the plugin tell it was
loaded into the plugin host?" is answered by the same delivery:

* a **register-time** record (written to ``<log>.register`` so the per-invocation log keeps exactly
  one line per hook call): the pid, ``HERMES_PLUGIN_HOST_PROCESS``, the concrete ``ctx`` class and
  its public surface, and what ``hermes_cli.plugin_isolation.isolation_mode()`` answers there;
* the **full payload** of the event as the hook received it (every field, raw, truncated only in
  length) plus whether the heartbeat stamp is present as an attribute or as a key — so the two
  candidate detectors can be compared on real deliveries instead of being assumed.

Nothing about the plugin under test is stubbed: the probe is an extra observer, and the two
callbacks see the identical kwargs because the delivery manager builds them per invocation.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

PROBE_NAME = "p2-hook-probe"

_PROBE_INIT = '''"""P2' / P2c hook-argument probe (generated by tests/host_e2e/probe_plugin.py)."""

import json
import os

_LOG = {log_path!r}
_REGISTER_LOG = _LOG + ".register"


def _write(path, rec):
    try:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False, default=str) + "\\n")
    except Exception:
        pass


def _record(rec):
    _write(_LOG, rec)


def _try(label, fn):
    try:
        return {{"call": label, "ok": True, "value": repr(fn())[:160]}}
    except Exception as exc:
        return {{"call": label, "ok": False, "error": "%s: %s" % (type(exc).__name__, exc)[:200]}}


def _isolation():
    try:
        from hermes_cli.plugin_isolation import isolation_mode

        return isolation_mode()
    except Exception as exc:
        return "unavailable:%s" % type(exc).__name__


def _public(ctx):
    return sorted(name for name in dir(ctx) if not name.startswith("_"))


def _payload(event):
    """Every field the host handed over for this event, verbatim (values are repr'd, not summarised)."""
    if isinstance(event, dict):
        return {{str(key): repr(value)[:200] for key, value in sorted(event.items())}}
    return {{"__object__": type(event).__name__}}


def register(ctx):
    """Record what register() can see *before* anything is registered, then subscribe."""
    _write(_REGISTER_LOG, {{
        "phase": "register",
        "pid": os.getpid(),
        "host_process": os.environ.get("HERMES_PLUGIN_HOST_PROCESS"),
        "env_has_flag": "HERMES_PLUGIN_HOST_PROCESS" in os.environ,
        "module_file": __file__,
        "ctx_type": type(ctx).__name__,
        "ctx_public": _public(ctx),
        "ctx_has_get_config": callable(getattr(ctx, "get_config", None)),
        "mode_seen_by_callback": _isolation(),
        "hook_calls_before_register": 0,
    }})
    ctx.register_hook("pre_gateway_dispatch", pre_gateway_dispatch)


def pre_gateway_dispatch(event=None, gateway=None, session_store=None, **kwargs):
    meta = getattr(event, "metadata", None)
    key = str(meta.get("gateway_session_key") or "") if isinstance(meta, dict) else ""
    _record({{
        "pid": os.getpid(),
        "host_process": os.environ.get("HERMES_PLUGIN_HOST_PROCESS"),
        # NOT a mode detector: hermes_cli.plugin_isolation.isolation_mode() is documented to return
        # "in_process" whenever HERMES_PLUGIN_HOST_PROCESS is set, i.e. always inside the host.
        # The real detector is pid/host_process plus the *types* below.
        "mode_seen_by_callback": _isolation(),
        "event_type": type(event).__name__,
        "event_is_mapping": isinstance(event, dict),
        "heartbeat_session_id": getattr(event, "_heartbeat_session_id", None),
        "heartbeat_id_is_a_key": isinstance(event, dict) and "_heartbeat_session_id" in event,
        "heartbeat_attr_present": hasattr(event, "_heartbeat_session_id"),
        "event_keys": sorted(str(key) for key in event) if isinstance(event, dict) else None,
        "event_payload": _payload(event),
        "session_key": key,
        "gateway_type": type(gateway).__name__,
        "store_type": type(session_store).__name__,
        "gateway_repr": repr(gateway)[:160],
        "store_repr": repr(session_store)[:160],
        "calls": [
            _try("session_store.peek_session_id", lambda: session_store.peek_session_id(key)),
            _try("gateway._is_session_running", lambda: gateway._is_session_running(key)),
            _try("gateway.session_store.peek_session_id",
                 lambda: gateway.session_store.peek_session_id(key)),
        ],
    }})
    return None
'''

_PROBE_MANIFEST = f'''name: {PROBE_NAME}
version: "0.1.0"
manifest_version: 2
description: "P2' / P2c probe: records what the pre_gateway_dispatch arguments and ctx look like."
author: "Hermes dev profile (card t_9ddbe572, t_195a2515)"
provides_hooks:
  - pre_gateway_dispatch
'''

#: Suffix the probe appends for the one-per-load register record (the hook log stays one line/call).
REGISTER_SUFFIX = ".register"


def register_log_path(log_path: Path) -> Path:
    """Where the probe writes its register-time record for this scenario."""
    return Path(str(Path(log_path)) + REGISTER_SUFFIX)


def install_probe_plugin(log_path: Path) -> Path:
    """Install the probe beside the plugin under test, in the isolated home, and return its dir."""
    import support

    target = support.ISO_HOME / "plugins" / PROBE_NAME
    target.mkdir(parents=True, exist_ok=True)
    (target / "plugin.yaml").write_text(_PROBE_MANIFEST, encoding="utf-8")
    (target / "__init__.py").write_text(_PROBE_INIT.format(log_path=str(Path(log_path))),
                                        encoding="utf-8")
    return target


def _read_lines(path: Path) -> List[Dict[str, Any]]:
    path = Path(path)
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            records.append(json.loads(line))
    return records


def read_records(log_path: Path) -> List[Dict[str, Any]]:
    """Every hook-invocation record written so far (one JSON object per real hook invocation)."""
    return _read_lines(log_path)


def read_register_records(log_path: Path) -> List[Dict[str, Any]]:
    """Every register-time record written so far (one per successful/attempted plugin load)."""
    return _read_lines(register_log_path(log_path))
